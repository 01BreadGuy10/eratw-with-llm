def build():
    out = [c + "\n" for c in COMMENT]
    for t in BODY:
        out.append(p(t))
    for t in BODY_2B_OPEN:
        out.append(p(t))
    out.append("IF LLM_CALLME_SHOW(LLM_CID) == " + Q + Q + "\n")
    for t in BODY_2B_TAIL:
        out.append("\t" + p(t))
    out.append("ENDIF\n")
    for t in BODY_3:
        out.append(p(t))
    out.append("\n")
    return out


def main():
    apply = "--apply" in sys.argv
    show = "--show" in sys.argv

    with open(PATH, encoding="utf-8") as f:
        lines = f.readlines()

    i_hdr = [i for i, l in enumerate(lines) if MARK_HDR in l]
    i_e1 = [i for i, l in enumerate(lines) if MARK_END in l]
    i_e2 = [i for i, l in enumerate(lines) if MARK_END2 in l]
    print("含 标题 : %s" % [i + 1 for i in i_hdr])
    print("含 ③ 段 : %s" % [i + 1 for i in i_e1])
    print("含 ④ 段 : %s" % [i + 1 for i in i_e2])
    if len(i_hdr) != 1 or len(i_e1) != 1:
        print("❌ 锚点不唯一 —— 中止")
        return 1

    hdr, end = i_hdr[0], i_e1[0]
    start = hdr
    for k in range(hdr, max(0, hdr - 14), -1):
        if "玩家自报的身份" in lines[k]:
            start = k
            break
    while start > 0 and lines[start - 1].strip() == "":
        start -= 1

    blk = build()
    print("\n删除 第 %d ~ %d 行（%d 行）→ 插入 %d 行"
          % (start + 1, end, end - start, len(blk)))

    if show:
        print("\n── 新块内容（去掉 ERB 包装后）──")
        for l in blk:
            s = l.rstrip("\n")
            if s.startswith(";"):
                print("   " + s)
            elif s.startswith("IF ") or s.strip() == "ENDIF":
                print("   " + s)
            else:
                s = s.replace("REF_PROMPT += @" + Q + "\\n", "").rstrip(Q)
                print("     " + s)

    if not apply:
        print("\n（dry-run。加 --apply 才写入）")
        return 0

    new_lines = lines[:]
    new_lines[start:end] = blk
    with open(PATH, "w", encoding="utf-8", newline="") as f:
        f.write("".join(new_lines))
    print("\n✅ 已写入。行数 %d -> %d" % (len(lines), len(new_lines)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
